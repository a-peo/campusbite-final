#!/usr/bin/env node
/*
 * Bundles the ES modules in js/ into a single classic script (js/app.bundle.js).
 *
 * Why: browsers refuse to load <script type="module"> and its imports from a
 * file:// page, so the app needs a plain script to work when index.html is
 * opened directly from disk. Run `node build.js` after editing any file in js/.
 */
const fs = require("node:fs");
const path = require("node:path");

const ROOT = __dirname;
const ENTRY = "js/app.js";
const OUT = "js/app.bundle.js";

const define = (id) => {
  const source = fs.readFileSync(path.join(ROOT, id), "utf8");
  const exported = [];

  let code = source.replace(
    /import\s*\{([\s\S]*?)\}\s*from\s*["']([^"']+)["'];?/g,
    (_match, names, spec) => {
      const target = path.posix.normalize(path.posix.join(path.posix.dirname(id), spec));
      return `const {${names}} = __require(${JSON.stringify(target)});`;
    }
  );

  if (/^\s*import\s/m.test(code)) {
    throw new Error(`${id}: only named "import { ... } from" statements are supported`);
  }

  code = code.replace(
    /^export\s+(async\s+function|function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm,
    (_match, kind, name) => {
      exported.push(name);
      return `${kind} ${name}`;
    }
  );

  if (/^export\b/m.test(code)) {
    throw new Error(`${id}: unsupported export form`);
  }

  const footer = exported.length ? `\n  Object.assign(__exports, { ${exported.join(", ")} });\n` : "";
  return `__define(${JSON.stringify(id)}, function (__require, __exports) {\n${code}${footer}});\n`;
};

const files = ["js/backend.js", "js/api.js", "js/ui.js",
  "js/pages/auth.js", "js/pages/student.js", "js/pages/staff.js",
  "js/pages/admin.js", "js/pages/profile.js", "js/app.js"];

const bundle = `/* Generated by build.js - do not edit. Source lives in js/ (entry: ${ENTRY}). */
(function () {
  "use strict";
  const definitions = Object.create(null);
  const cache = Object.create(null);

  function __define(id, factory) {
    definitions[id] = factory;
  }

  function __require(id) {
    if (cache[id]) return cache[id];
    const factory = definitions[id];
    if (!factory) throw new Error("Module not found: " + id);
    const exports = (cache[id] = {});
    factory(__require, exports);
    return exports;
  }

${files.map(define).join("\n")}
  __require(${JSON.stringify(ENTRY)});
})();
`;

fs.writeFileSync(path.join(ROOT, OUT), bundle);
console.log(`Wrote ${OUT} (${(bundle.length / 1024).toFixed(1)} kB)`);
